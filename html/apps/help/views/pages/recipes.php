<h2 id="voice-control">Voice Control</h2>

<p>Cook hands-free with intelligent voice navigation and control.</p>

<div class="help-step">
    <div class="help-step-number">1</div>
    <h4>Activating Voice Control</h4>
    <ol>
        <li>Open any recipe</li>
        <li>Click the <strong>"Voice Mode"</strong> button</li>
        <li>Allow microphone access when prompted</li>
        <li>Wait for the "Ready" confirmation</li>
    </ol>
</div>

<div class="help-step">
    <div class="help-step-number">2</div>
    <h4>Voice Commands</h4>
    <div class="help-feature-grid">
        <div class="help-feature-card">
            <h4>Navigation Commands</h4>
            <ul>
                <li><strong>"Next step"</strong> - Move to next instruction</li>
                <li><strong>"Previous step"</strong> - Go back one step</li>
                <li><strong>"Go to step 3"</strong> - Jump to specific step</li>
                <li><strong>"Start over"</strong> - Return to beginning</li>
            </ul>
        </div>
        
        <div class="help-feature-card">
            <h4>Timer Commands</h4>
            <ul>
                <li><strong>"Set timer 5 minutes"</strong> - Start countdown</li>
                <li><strong>"How much time left?"</strong> - Check timer</li>
                <li><strong>"Cancel timer"</strong> - Stop current timer</li>
                <li><strong>"Add 2 minutes"</strong> - Extend timer</li>
            </ul>
        </div>
        
        <div class="help-feature-card">
            <h4>Information Commands</h4>
            <ul>
                <li><strong>"Read ingredients"</strong> - List all ingredients</li>
                <li><strong>"How many servings?"</strong> - Recipe yield info</li>
                <li><strong>"Cooking time?"</strong> - Total time needed</li>
                <li><strong>"Repeat step"</strong> - Re-read current step</li>
            </ul>
        </div>
        
        <div class="help-feature-card">
            <h4>Control Commands</h4>
            <ul>
                <li><strong>"Pause"</strong> - Pause voice mode</li>
                <li><strong>"Resume"</strong> - Continue voice mode</li>
                <li><strong>"Stop voice"</strong> - Exit voice mode</li>
                <li><strong>"Help"</strong> - List available commands</li>
            </ul>
        </div>
    </div>
</div>

<div class="help-info">
