<h2 id="data-export">Data Import/Export</h2>

<p>Manage your genealogy data with standard file formats.</p>

<div class="help-step">
    <div class="help-step-number">1</div>
    <h4>Exporting Your Data</h4>
    <ol>
        <li>Go to <strong>"Export Data"</strong> in settings</li>
        <li>Choose export format:
            <ul>
                <li><strong>GEDCOM:</strong> Standard genealogy format</li>
                <li><strong>PDF:</strong> Printable family tree charts</li>
                <li><strong>CSV:</strong> Spreadsheet format for analysis</li>
                <li><strong>JSON:</strong> Data backup format</li>
            </ul>
        </li>
        <li>Select data to include (people, documents, photos)</li>
        <li>Download the exported file</li>
    </ol>
</div>

<div class="help-step">
    <div class="help-step-number">2</div>
    <h4>Importing Data</h4>
    <ol>
        <li>Prepare your data file (GEDCOM or CSV)</li>
        <li>Click <strong>"Import Data"</strong></li>
        <li>Upload your file</li>
        <li>Review and map data fields</li>
        <li>Choose merge or create new tree option</li>
        <li>Confirm import and review results</li>
    </ol>
</div>

