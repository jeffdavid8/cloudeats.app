        <li><strong>Hourly Forecasts:</strong> Every hour</li>
        <li><strong>Daily Forecasts:</strong> Twice daily (morning/evening)</li>
        <li><strong>Severe Weather Alerts:</strong> Immediate updates</li>
        <li><strong>Radar Images:</strong> Every 5-10 minutes</li>
    </ul>
